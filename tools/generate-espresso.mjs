#!/usr/bin/env node
// Generate app/vendor/espresso.css from frappe-ui's token data, and vendor the
// fonts the UI uses. Regenerate after a frappe-ui upgrade:
//
//   node tools/generate-espresso.mjs [path/to/node_modules/frappe-ui]
//
// The default path is the frappe-ui checkout pi remote uses. The generated
// files are committed: the page must work with no build step and no CDN.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const VENDOR = join(ROOT, "app", "vendor");
const FONT_DIR = join(VENDOR, "fonts");

const frappe_ui = process.argv[2] ?? "/home/stravo1/projects/pi-remote/node_modules/frappe-ui";
const frappeVersion = JSON.parse(readFileSync(join(frappe_ui, "..", "frappe-ui", "package.json"), "utf8")).version;

const { cssVariables, radius } = await import(
  createRequire(import.meta.url).resolve(join(frappe_ui, "tailwind", "tokens.js"))
);

function declarations(variables) {
  return Object.entries(variables)
    .map(([name, value]) => `\t${name}: ${value};`)
    .join("\n");
}

// The app is dark only, so the dark semantic layer goes straight into :root.
const radiusDeclarations = Object.entries(radius)
  .map(([step, value]) => `\t--radius-${step}: ${value};`)
  .join("\n");

const css = `/* Generated by tools/generate-espresso.mjs from frappe-ui ${frappeVersion}.
 * Do not edit by hand; run the generator instead. */

:root {
${radiusDeclarations}
${declarations(cssVariables.dark)}
}
`;

mkdirSync(FONT_DIR, { recursive: true });

const interSource = join(frappe_ui, "src", "fonts", "Inter", "Inter.var.woff2");
const interTarget = join(FONT_DIR, "Inter.var.woff2");
copyFileSync(interSource, interTarget);

const jetbrainsSource = join(
  frappe_ui,
  "..",
  "@fontsource-variable",
  "jetbrains-mono",
  "files",
  "jetbrains-mono-latin-wght-normal.woff2",
);
const jetbrainsTarget = join(FONT_DIR, "jetbrains-mono-latin.var.woff2");
copyFileSync(jetbrainsSource, jetbrainsTarget);

const fonts = `/* Generated by tools/generate-espresso.mjs; the woff2 files sit next to this. */

@font-face {
	font-family: "InterVar";
	font-weight: 100 900;
	font-display: swap;
	font-style: normal;
	src: url("fonts/Inter.var.woff2") format("woff2-variations");
}

@font-face {
	font-family: "JetBrains Mono Variable";
	font-weight: 100 800;
	font-display: swap;
	font-style: normal;
	src: url("fonts/jetbrains-mono-latin.var.woff2") format("woff2-variations");
}
`;

writeFileSync(join(VENDOR, "espresso.css"), css);
writeFileSync(join(VENDOR, "fonts.css"), fonts);

for (const file of ["espresso.css", "fonts.css", relative(VENDOR, interTarget), relative(VENDOR, jetbrainsTarget)]) {
  console.log(`wrote app/vendor/${file}`);
}
